import { Router } from 'express';
import authRoutes from './authRoutes.js';
import examRoutes from './examRoutes.js';
import testRoutes from './testRoutes.js';
import resultRoutes from './resultRoutes.js';
import adaptiveRoutes from './adaptiveRoutes.js';
import aiRoutes from './aiRoutes.js';
import performanceRoutes from './performanceRoutes.js';
import adminRoutes from './adminRoutes.js';
import syllabusRoutes from './syllabusRoutes.js';
import questionRoutes from './questionRoutes.js';
import { PerformanceController } from '../controllers/performanceController.js';
import { AIController } from '../controllers/aiController.js';
import { AdaptiveController } from '../controllers/adaptiveController.js';
import { authenticateJWT } from '../middleware/authMiddleware.js';
const router = Router();
router.use('/auth', authRoutes);
router.use('/exams', examRoutes);
router.use('/questions', questionRoutes);
router.use('/tests', testRoutes);
router.use('/results', resultRoutes);
router.use('/adaptive', adaptiveRoutes);
router.use('/ai', aiRoutes);
router.use('/performance', performanceRoutes);
router.use('/admin', adminRoutes);
router.use('/syllabus', syllabusRoutes);
// Direct top-level convenience aliases
router.get('/dashboard', authenticateJWT, PerformanceController.getDashboardData);
router.get('/history', authenticateJWT, PerformanceController.getHistory);
router.get('/weaknesses', authenticateJWT, AdaptiveController.getWeaknessProfile);
router.get('/ai-analysis', authenticateJWT, AIController.getAnalysis);
router.get('/ai-analysis/:attemptId', authenticateJWT, AIController.getAnalysis);
export default router;
